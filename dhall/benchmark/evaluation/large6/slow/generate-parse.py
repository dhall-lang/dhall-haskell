#!/usr/bin/env python3
"""Regenerate slow/parse.dhall (artificial ~0.5s parse burden).

Keep NESTING / BLOCK_COUNT in sync with Bench.ImportTrees.slowParseDhallContents.
The evaluation benchmark also generates this file during setup if it is missing.
"""

from pathlib import Path

NESTING = 8
BLOCK_COUNT = 81270
OUT = Path(__file__).with_name("parse.dhall")

header = (
    "-- Artificial parse burden: ~0.5 seconds to parse this file (cold, no cache).\n"
    "-- The cost is in the lexer/parser walking ~1.3M lines of nested block comments;\n"
    "-- the normalized value is just `True`.\n"
    "-- Generated by generate-parse.py / evaluation-benchmark setup.\n"
)
block = ("{-\n" * NESTING) + ("-}\n" * NESTING)
OUT.write_text(header + block * BLOCK_COUNT + "True\n")
print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {BLOCK_COUNT * NESTING * 2 + 5} lines)")
